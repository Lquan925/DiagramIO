-- Match owner filtering and the stable newest-first order, including timestamp ties.
CREATE INDEX idx_diagrams_owner_updated_id
    ON diagrams (owner_id, updated_at DESC, id DESC);

-- Keep type-filtered pages ordered without sorting all diagrams owned by a user.
CREATE INDEX idx_diagrams_owner_type_updated_id
    ON diagrams (owner_id, diagram_type, updated_at DESC, id DESC);

-- Public pages and counts only need entries for public diagrams.
CREATE INDEX idx_diagrams_public_updated_id
    ON diagrams (updated_at DESC, id DESC)
    WHERE is_public = TRUE;

-- A B-tree cannot accelerate leading-wildcard title searches. Match the UPPER(title)
-- expression generated by Spring Data's ContainingIgnoreCase queries.
-- Keep extension objects in public so custom Flyway schemas can share an existing
-- installation without relying on public being present in their search_path.
CREATE EXTENSION IF NOT EXISTS pg_trgm WITH SCHEMA public;

CREATE INDEX idx_diagrams_title_upper_trgm
    ON diagrams USING gin (UPPER(title) public.gin_trgm_ops);

-- The owner prefix of idx_diagrams_owner_updated_id also serves owner-only lookups.
DROP INDEX idx_diagrams_owner;
